using Microsoft.EntityFrameworkCore;
using Npgsql;
using _3K.Core.Entities;
using _3K.Infrastructure.Data;

namespace _3K.Application.Tests;

/// <summary>
/// <c>scripts/database/roller/Uygulama_Rolu.sql</c>: API'nin bağlandığı rol uygulamanın yaptığı her şeyi yapabilir
/// (okuma, yazma, satır kilidi, advisory lock, LISTEN/NOTIFY, tetikleyicili yazma) ama şemaya, rollere ve sunucuya
/// dokunamaz. Yalnız izole test sunucusunda, kendi geçici veritabanında çalışır.
/// </summary>
public sealed class UygulamaRoluBetigiPostgresTests
{
    private const string Rol = "uck_uygulama";
    private const string SahipRol = "rol_test_tablo_sahibi";
    private const string YetkiYok = "42501";

    [PostgresRaporFact, Trait("Category", "Postgres")]
    public async Task UygulamaRolu_VeriyiOkurYazarAmaSemayaRolleraVeSunucuyaDokunamaz()
    {
        await InDatabase(async (yonetici, uygulama) =>
        {
            // Canlıdaki kalıp: tetikleyici fonksiyonu sahibinin yetkisiyle çalışır ve PUBLIC'e kapalıdır; uygulama
            // rolünün ne fonksiyonda ne de yazdığı kuyruk tablosunda izni vardır.
            await CalistirAsync(yonetici, """
                CREATE TABLE "RolTestKuyrugu" ("RolId" integer NOT NULL);
                CREATE FUNCTION rol_test_tetikle() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
                    SET search_path = pg_catalog, public AS $f$
                BEGIN
                    INSERT INTO public."RolTestKuyrugu" ("RolId") VALUES (NEW."Id");
                    PERFORM pg_notify('rol_test', '');
                    RETURN NEW;
                END $f$;
                REVOKE ALL ON FUNCTION rol_test_tetikle() FROM PUBLIC;
                CREATE TRIGGER "TR_RolTest" AFTER INSERT ON "Roller" FOR EACH ROW EXECUTE FUNCTION rol_test_tetikle();
                CREATE TABLE "BetikKayitlari" ("BetikAdi" text PRIMARY KEY, "UygulamaTarihi" timestamp NOT NULL, "Uygulayan" text NOT NULL);
                """);
            // Canlıdaki durum: tabloların sahibi ve şema betiklerini çalıştıran rol süper kullanıcı değildir.
            await CalistirAsync(yonetici, $"""
                CREATE ROLE {SahipRol} NOLOGIN;
                CREATE TABLE "RolTestSahipOnce" ("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Ad" text NOT NULL);
                ALTER TABLE "RolTestSahipOnce" OWNER TO {SahipRol};
                """);

            // İki kez: betik tekrar çalıştırılabilir olmalı.
            await BetigiCalistirAsync(yonetici);
            await BetigiCalistirAsync(yonetici);
            await CalistirAsync(yonetici, $"""
                ALTER ROLE {Rol} PASSWORD 'yerel-test-rol';
                REVOKE ALL ON "RolTestKuyrugu" FROM {Rol};
                -- Betikten SONRA, şema betiklerindeki gibi yönetici rolüyle açılan tablo: varsayılan izinle açılmalı.
                CREATE TABLE "RolTestSonradan" ("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Ad" text NOT NULL);
                -- Aynısı tablo sahibi rolle: şema PUBLIC'e kapatıldıktan sonra da tablo açabilmeli ve tablo uygulamaya açılmalı.
                SET ROLE {SahipRol};
                CREATE TABLE "RolTestSahipSonra" ("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Ad" text NOT NULL);
                RESET ROLE;
                """);

            await using var baglanti = new NpgsqlConnection(uygulama);
            await baglanti.OpenAsync();
            Assert.Equal(Rol, await SkalerAsync<string>(baglanti, "SELECT current_user::text"));
            Assert.False(await SkalerAsync<bool>(baglanti,
                "SELECT rolsuper OR rolcreatedb OR rolcreaterole OR rolreplication OR rolbypassrls FROM pg_roles WHERE rolname = current_user"));

            // Uygulamanın yaptığı işler: EF ile kimlik kolonlu ekleme (tetikleyici çalışır), güncelleme, satır kilidi, silme.
            var secenekler = new DbContextOptionsBuilder<AppDbContext>().UseNpgsql(uygulama).Options;
            int rolId;
            await using (var db = new AppDbContext(secenekler))
            {
                Assert.True(await db.Database.CanConnectAsync());
                var rol = new Rol { Ad = "Sentetik rol" };
                db.Roller.Add(rol);
                await db.SaveChangesAsync();
                rolId = rol.Id;
                rol.Ad = "Sentetik rol 2";
                await db.SaveChangesAsync();
                await using var islem = await db.Database.BeginTransactionAsync();
                Assert.Equal(1, await db.Roller.FromSqlInterpolated($"SELECT * FROM \"Roller\" WHERE \"Id\" = {rolId} FOR UPDATE").CountAsync());
                await db.Database.ExecuteSqlRawAsync("SELECT pg_advisory_xact_lock(3006195001::bigint)");
                await islem.CommitAsync();
            }
            Assert.Equal(1L, await SkalerAsync<long>(yonetici, $"SELECT count(*) FROM \"RolTestKuyrugu\" WHERE \"RolId\" = {rolId}"));
            await CalistirAsync(baglanti, "LISTEN rol_test; SELECT pg_notify('rol_test', ''); UNLISTEN rol_test;");
            await CalistirAsync(baglanti, "CREATE TEMP TABLE gecici (i integer); DROP TABLE gecici;");
            foreach (var tablo in new[] { "RolTestSonradan", "RolTestSahipOnce", "RolTestSahipSonra" })
                await CalistirAsync(baglanti, $"""INSERT INTO "{tablo}" ("Ad") VALUES ('a'); UPDATE "{tablo}" SET "Ad" = 'b'; DELETE FROM "{tablo}";""");
            await CalistirAsync(baglanti, $"DELETE FROM \"Roller\" WHERE \"Id\" = {rolId}");

            // Uygulamanın yapmaması gerekenler: hepsi "yetki yok" ile reddedilir.
            foreach (var yasak in new[]
            {
                "CREATE TABLE public.kacak (i integer)",
                """DROP TABLE "Roller" CASCADE""",
                """ALTER TABLE "Roller" ADD COLUMN kacak integer""",
                """TRUNCATE "Roller" CASCADE""",
                """CREATE TRIGGER kacak AFTER INSERT ON "Roller" FOR EACH ROW EXECUTE FUNCTION rol_test_tetikle()""",
                "SELECT rol_test_tetikle()",
                """SELECT * FROM "RolTestKuyrugu" """,
                """SELECT * FROM "BetikKayitlari" """,
                """DELETE FROM "BetikKayitlari" """,
                "COPY (SELECT 1) TO PROGRAM 'echo kacak'",
                """COPY "Roller" TO '/tmp/kacak.csv'""",
                "SELECT pg_read_file('postgresql.conf')",
                "SELECT pg_ls_dir('.')",
                "CREATE ROLE kacak_rol",
                $"ALTER ROLE {Rol} SUPERUSER",
                "CREATE DATABASE kacak_db",
                "CREATE SCHEMA kacak",
                "ALTER SYSTEM SET log_statement = 'none'",
            })
            {
                var hata = await Assert.ThrowsAsync<PostgresException>(() => CalistirAsync(baglanti, yasak));
                Assert.True(hata.SqlState == YetkiYok, $"{yasak} → {hata.SqlState}: {hata.MessageText}");
            }

            Assert.Equal("Uygulama_Rolu", await SkalerAsync<string>(yonetici, """SELECT "BetikAdi" FROM "BetikKayitlari" """));
        });
    }

    private static async Task BetigiCalistirAsync(NpgsqlConnection yonetici)
    {
        var dizin = new DirectoryInfo(AppContext.BaseDirectory);
        string Yol(DirectoryInfo d) => Path.Combine(d.FullName, "scripts", "database", "roller", "Uygulama_Rolu.sql");
        while (dizin != null && !File.Exists(Yol(dizin)))
            dizin = dizin.Parent;
        Assert.NotNull(dizin);
        await CalistirAsync(yonetici, await File.ReadAllTextAsync(Yol(dizin)));
    }

    private static async Task CalistirAsync(NpgsqlConnection baglanti, string sql)
    {
        await using var komut = new NpgsqlCommand(sql, baglanti);
        await komut.ExecuteNonQueryAsync();
    }

    private static async Task<T> SkalerAsync<T>(NpgsqlConnection baglanti, string sql)
    {
        await using var komut = new NpgsqlCommand(sql, baglanti);
        return (T)(await komut.ExecuteScalarAsync())!;
    }

    /// <summary>Geçici veritabanını EF modeliyle kurar; teste yönetici bağlantısını ve uygulama rolünün bağlantı cümlesini verir.</summary>
    private static async Task InDatabase(Func<NpgsqlConnection, string, Task> test)
    {
        var yoneticiCumlesi = new NpgsqlConnectionStringBuilder(Environment.GetEnvironmentVariable("THREEK_TEST_POSTGRES"));
        Assert.True(yoneticiCumlesi.Host is "127.0.0.1" or "localhost");
        Assert.Equal(55439, yoneticiCumlesi.Port);
        Assert.Equal("postgres", yoneticiCumlesi.Database);
        var veritabani = $"uygulama_rolu_tests_{Guid.NewGuid():N}";
        await using var sunucu = new NpgsqlConnection(yoneticiCumlesi.ConnectionString);
        await sunucu.OpenAsync();
        await CalistirAsync(sunucu, $"CREATE DATABASE \"{veritabani}\"");
        try
        {
            yoneticiCumlesi.Database = veritabani;
            await using (var db = new AppDbContext(new DbContextOptionsBuilder<AppDbContext>().UseNpgsql(yoneticiCumlesi.ConnectionString).Options))
                await db.Database.EnsureCreatedAsync();

            var uygulamaCumlesi = new NpgsqlConnectionStringBuilder(yoneticiCumlesi.ConnectionString)
            {
                Username = Rol,
                Password = "yerel-test-rol"
            };
            await using var yonetici = new NpgsqlConnection(yoneticiCumlesi.ConnectionString);
            await yonetici.OpenAsync();
            await test(yonetici, uygulamaCumlesi.ConnectionString);
        }
        finally
        {
            NpgsqlConnection.ClearAllPools();
            // Yalnız bu testin oluşturduğu, sabit önek + GUID isimli sentetik veritabanı ve izole sunucudaki test rolleri kaldırılır.
            Assert.Matches("^uygulama_rolu_tests_[a-f0-9]{32}$", veritabani);
            await CalistirAsync(sunucu, $"DROP DATABASE \"{veritabani}\" WITH (FORCE)");
            await CalistirAsync(sunucu, $"DROP ROLE IF EXISTS {Rol}");
            await CalistirAsync(sunucu, $"DROP ROLE IF EXISTS {SahipRol}");
        }
    }
}
