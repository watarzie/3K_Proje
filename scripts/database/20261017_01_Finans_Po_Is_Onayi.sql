-- =====================================================================================
-- PO öncesi iş onayı (İşlem Onay Merkezi kodu FINANS_PO_IS_ONAYI).
--
-- Üretimden gelen proje kalemleri (Ana ambalaj, Sarf kereste, İlave, İç sandık, Saha, Yedek, Diğer üretim) PO'ya
-- bağlanmadan önce onaylanır. Kullanıcı kalemleri "Onaya gönder" ile proje × iş türü × para birimi grubu olarak onaya
-- sunar; talep Onay Merkezi'ne düşer. Özel iş ve düzenli iş (iş türü 8) onay istemez.
--
-- "FinansPoOnayTalepleri": onaya sunulan grubun değişmez görüntüsü (kalemler, ölçü, m³, tutar). Karar
--   "OnayBekleyenIslemler" kaydındadır (ReferansTipi = FinansPoOnayTalebi).
-- "FinansIsKayitlari": "PoOnayTalebiId" (son talep, restrict), "PoOnayNetTutar" ve "PoOnayParaBirimi" (onaylanan değer;
--   kaydın güncel net tutarı veya para birimi farklıysa onay düşer), "PoOnayTarihi", "PoOnaylayanKullaniciId".
-- "OnayOperasyonKurallari": FINANS_PO_IS_ONAYI açık ("Onay gerekli") eklenir. "OnayIslemYetkileri": onaycı rolü
--   yalnız Admin (Id 1); diğer onaycı roller İşlem Onay Merkezi > Sistem Kuralları ekranından seçilir.
--
-- Geçiş (yalnız kolonların eklendiği çalıştırmada): iptal edilmemiş bir PO'ya bağlı kalemi olan proje kayıtları onaylı
--   sayılır; onaylanan tutar kaydın o anki net tutarıdır (FinansTutarKurallari.IsNet ile aynı hesap), onaylayan boştur.
--   Sipariş bekleyen kayıtlar onaysız başlar.
--
-- Tekrar çalıştırılabilir: tekrarında kural kaydı ve onaycı roller (yöneticinin kararı) değişmez, geçiş yeniden
-- uygulanmaz. Yıkıcı değildir; yeni API ile birlikte uygulanır (eski API yeni kolonları okumaz).
-- =====================================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS "FinansPoOnayTalepleri" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "ProjeId" integer,
    "ProjeNo" character varying(100) NOT NULL,
    "Musteri" character varying(250) NOT NULL,
    "IsTuru" integer NOT NULL,
    "ParaBirimi" character varying(3) NOT NULL,
    "KalemSayisi" integer NOT NULL,
    "NetTutar" numeric(18,2) NOT NULL,
    "OnizlemeJson" jsonb NOT NULL,
    "OnizlemeHash" character varying(64) NOT NULL,
    "TalepEdenKullaniciId" integer NOT NULL,
    "UygulamaTarihi" timestamp without time zone,
    "CreatedDate" timestamp without time zone NOT NULL,
    "UpdatedDate" timestamp without time zone,
    "CreatedBy" text,
    "UpdatedBy" text,
    CONSTRAINT "PK_FinansPoOnayTalepleri" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_FinansPoOnayTalepleri_OnizlemeJson" CHECK (jsonb_typeof("OnizlemeJson" -> 'kalemler') = 'array' AND jsonb_array_length("OnizlemeJson" -> 'kalemler') > 0),
    CONSTRAINT "CK_FinansPoOnayTalepleri_Tutar" CHECK ("KalemSayisi" > 0 AND "NetTutar" > 0)
);

CREATE INDEX IF NOT EXISTS "IX_FinansPoOnayTalepleri_ProjeId" ON "FinansPoOnayTalepleri" ("ProjeId");

DO $$
DECLARE
    ilk_calistirma boolean;
    onaylanan integer;
    onaysiz integer;
BEGIN
    ilk_calistirma := NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = 'FinansIsKayitlari' AND column_name = 'PoOnayTalebiId');

    ALTER TABLE "FinansIsKayitlari" ADD COLUMN IF NOT EXISTS "PoOnayTalebiId" integer NULL;
    ALTER TABLE "FinansIsKayitlari" ADD COLUMN IF NOT EXISTS "PoOnayNetTutar" numeric(18,2) NULL;
    ALTER TABLE "FinansIsKayitlari" ADD COLUMN IF NOT EXISTS "PoOnayParaBirimi" character varying(3) NULL;
    ALTER TABLE "FinansIsKayitlari" ADD COLUMN IF NOT EXISTS "PoOnayTarihi" timestamp without time zone NULL;
    ALTER TABLE "FinansIsKayitlari" ADD COLUMN IF NOT EXISTS "PoOnaylayanKullaniciId" integer NULL;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_FinansIsKayitlari_FinansPoOnayTalepleri_PoOnayTalebiId') THEN
        ALTER TABLE "FinansIsKayitlari"
            ADD CONSTRAINT "FK_FinansIsKayitlari_FinansPoOnayTalepleri_PoOnayTalebiId"
            FOREIGN KEY ("PoOnayTalebiId") REFERENCES "FinansPoOnayTalepleri" ("Id") ON DELETE RESTRICT;
    END IF;

    IF ilk_calistirma THEN
        UPDATE "FinansIsKayitlari" i
        SET "PoOnayNetTutar" = COALESCE(i."ManuelNetTutar",
                CASE WHEN i."AhsapBirimFiyatSnapshot" IS NOT NULL
                     THEN round(i."BirimFiyatSnapshot" * COALESCE(i."KontraM3", i."ToplamM3" - COALESCE(i."AhsapM3", 0))
                                + i."AhsapBirimFiyatSnapshot" * COALESCE(i."AhsapM3", 0), 2)
                     ELSE round(i."BirimFiyatSnapshot" * CASE i."FiyatlandirmaBirimiSnapshot"
                                                             WHEN 1 THEN i."Adet"
                                                             WHEN 2 THEN i."ToplamM3"
                                                             ELSE 1 END, 2)
                END),
            "PoOnayParaBirimi" = i."ParaBirimiSnapshot",
            "PoOnayTarihi" = now() AT TIME ZONE 'Europe/Istanbul'
        WHERE i."IsTuru" <> 8
          AND EXISTS (SELECT 1
                      FROM "FinansSiparisKalemleri" k
                      JOIN "FinansSiparisleri" s ON s."Id" = k."FinansSiparisId"
                      WHERE k."FinansIsKaydiId" = i."Id" AND NOT s."IptalEdildi");
        GET DIAGNOSTICS onaylanan = ROW_COUNT;

        SELECT count(*) INTO onaysiz
        FROM "FinansIsKayitlari" i
        WHERE i."IsTuru" <> 8 AND NOT i."IptalEdildi" AND i."KaynakAktif" AND i."PoOnayNetTutar" IS NULL;

        RAISE NOTICE 'PO öncesi iş onayı geçişi: PO''ya bağlı % proje kaydı onaylı sayıldı; % aktif proje kaydı onaysız başlıyor.',
            onaylanan, onaysiz;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS "IX_FinansIsKayitlari_PoOnayTalebiId" ON "FinansIsKayitlari" ("PoOnayTalebiId");

-- Kural ve ilk onaycı rol yalnız kural kaydı bu çalıştırmada eklenince yazılır; yöneticinin sonraki kararı korunur.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM "OnayOperasyonKurallari" WHERE "IslemKodu" = 'FINANS_PO_IS_ONAYI') THEN
        INSERT INTO "OnayOperasyonKurallari" ("IslemKodu", "OnayGerektirirMi", "CreatedDate", "CreatedBy")
        VALUES ('FINANS_PO_IS_ONAYI', true, now() AT TIME ZONE 'Europe/Istanbul', '20261017_01_Finans_Po_Is_Onayi.sql');

        INSERT INTO "OnayIslemYetkileri" ("IslemKodu", "RolId", "CreatedDate", "CreatedBy")
        SELECT 'FINANS_PO_IS_ONAYI', r."Id", now() AT TIME ZONE 'Europe/Istanbul', '20261017_01_Finans_Po_Is_Onayi.sql'
        FROM "Roller" r
        WHERE r."Id" = 1
          AND NOT EXISTS (SELECT 1 FROM "OnayIslemYetkileri" y WHERE y."IslemKodu" = 'FINANS_PO_IS_ONAYI' AND y."RolId" = r."Id");

        RAISE NOTICE 'FINANS_PO_IS_ONAYI kuralı açık eklendi; onaycı rol Admin. Diğer roller Onay Merkezi > Sistem Kuralları''ndan seçilir.';
    END IF;
END $$;

COMMIT;
