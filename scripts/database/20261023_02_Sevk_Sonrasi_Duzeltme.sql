-- unutulan ürün ekleme, ürün silme, sandıklar arası taşıma, Grid/3K işlemlerini geri alma.
--
-- 1) SandikDuzeltmeKayitlari tablosu: her düzeltmenin gerekçesi, açan/tamamlayan kullanıcı ve tarihleri, açılıştaki
--    sandık içeriği (JSON) ve tamamlanınca "önce → sonra" fark özeti. Sandıkta aynı anda tek açık kayıt olur (kısmi
--    benzersiz indeks). Sandık silinirse bağ boşalır, kayıt kalır; proje silinirse kayıt da silinir.
-- 2) İzin: sevk-sonrasi-duzeltme (Id 5259, MENU.SEVK_SONRASI_DUZELTME, ekran değil işlem izni; Route yok) Sandık
--    Yönetimi altına eklenir. Yalnız Admin W alır; başka rollere rol yönetiminden verilir. Bu izin olmadan sevkiyat
--    kaydı korunarak kilit açma (sandık/proje) 403 döner; sevkiyat geri alınarak açma eskisi gibi çalışır.
--
-- Yıkıcı değildir, tekrar çalıştırılabilir: tablo/indeks varsa eklenmez, düğüm varsa eklenmez, verilmiş izin
-- değiştirilmez. Id veya kod başka bir menü tanımına aitse hiçbir şey değiştirmeden durur. Yeni API'den önce uygulanır
-- (yeni API kilit açmada bu tabloya yazar). Finans/Ambalaj tablosuna dokunmaz.
-- =====================================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS "SandikDuzeltmeKayitlari" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "ProjeId" integer NOT NULL,
    "SandikId" integer,
    "SandikNo" text NOT NULL,
    "Gerekce" text NOT NULL,
    "AcanKullaniciId" integer NOT NULL,
    "AcilisTarihi" timestamp without time zone NOT NULL,
    "AcilisGoruntusu" text NOT NULL,
    "TamamlayanKullaniciId" integer,
    "TamamlanmaTarihi" timestamp without time zone,
    "FarkOzeti" text,
    "CreatedDate" timestamp without time zone NOT NULL,
    "UpdatedDate" timestamp without time zone,
    "CreatedBy" text,
    "UpdatedBy" text,
    CONSTRAINT "PK_SandikDuzeltmeKayitlari" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_SandikDuzeltmeKayitlari_Projeler_ProjeId" FOREIGN KEY ("ProjeId") REFERENCES "Projeler" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_SandikDuzeltmeKayitlari_Sandiklar_SandikId" FOREIGN KEY ("SandikId") REFERENCES "Sandiklar" ("Id") ON DELETE SET NULL
);

-- Betiğin 23.10.2026 ön sürümü "YeniSandikMi" kolonunu da ekliyordu (düzeltmeye sandık ekleme kaldırıldı). O sürümü
-- çalıştırmış veritabanında kolon kalırsa yeni kayıtlar NOT NULL hatası verir; kolon yalnız o denemeden kalmıştır.
ALTER TABLE "SandikDuzeltmeKayitlari" DROP COLUMN IF EXISTS "YeniSandikMi";

CREATE INDEX IF NOT EXISTS "IX_SandikDuzeltmeKayitlari_ProjeId" ON "SandikDuzeltmeKayitlari" ("ProjeId");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_SandikDuzeltmeKayitlari_SandikId_Acik" ON "SandikDuzeltmeKayitlari" ("SandikId") WHERE "TamamlanmaTarihi" IS NULL;

DO $$
DECLARE
    ust_id integer;
    sira integer;
BEGIN
    SELECT "Id" INTO ust_id FROM "MenuTanimlari" WHERE "Kod" = 'sandik-yonetimi';
    IF ust_id IS NULL THEN
        RAISE EXCEPTION 'sandik-yonetimi menü düğümü bulunamadı; betik durduruldu.';
    END IF;
    IF EXISTS (SELECT 1 FROM "MenuTanimlari" WHERE ("Id" = 5259 AND "Kod" <> 'sevk-sonrasi-duzeltme') OR ("Kod" = 'sevk-sonrasi-duzeltme' AND "Id" <> 5259)) THEN
        RAISE EXCEPTION '5259 numaralı menü tanımı veya sevk-sonrasi-duzeltme kodu başka bir kayda ait; betik durduruldu.';
    END IF;
    SELECT COALESCE(max("Sira"), 0) + 1 INTO sira FROM "MenuTanimlari" WHERE "ParentId" = ust_id;
    IF NOT EXISTS (SELECT 1 FROM "MenuTanimlari" WHERE "Kod" = 'sevk-sonrasi-duzeltme') THEN
        INSERT INTO "MenuTanimlari" ("Id", "Kod", "LabelKey", "Icon", "Route", "Sira", "ParentId", "CreatedDate", "CreatedBy")
        VALUES (5259, 'sevk-sonrasi-duzeltme', 'MENU.SEVK_SONRASI_DUZELTME', 'ri-edit-box-line', NULL, sira, ust_id,
                now() AT TIME ZONE 'Europe/Istanbul', '20261023_02_Sevk_Sonrasi_Duzeltme.sql');
    END IF;
    PERFORM setval(pg_get_serial_sequence('"MenuTanimlari"', 'Id'), (SELECT max("Id") FROM "MenuTanimlari"));
END $$;

-- Yalnız Admin W. Verilmiş izin değiştirilmez.
INSERT INTO "RolYetkileri" ("RolId", "MenuTanimiId", "YetkiTipiId", "CreatedDate", "CreatedBy")
SELECT r."Id", yeni."Id",
       (SELECT "Id" FROM "LookupYetkiTipleri" WHERE "Deger" = 'W'),
       now() AT TIME ZONE 'Europe/Istanbul', '20261023_02_Sevk_Sonrasi_Duzeltme.sql'
FROM "Roller" r
CROSS JOIN (SELECT "Id" FROM "MenuTanimlari" WHERE "Kod" = 'sevk-sonrasi-duzeltme') yeni
WHERE r."Id" = 1
  AND NOT EXISTS (
        SELECT 1 FROM "RolYetkileri" mevcut
        WHERE mevcut."RolId" = r."Id" AND mevcut."MenuTanimiId" = yeni."Id");

DO $$
DECLARE
    satir record;
BEGIN
    FOR satir IN
        SELECT r."Ad" AS rol, tip."Deger" AS seviye
        FROM "RolYetkileri" ry
        JOIN "Roller" r ON r."Id" = ry."RolId"
        JOIN "MenuTanimlari" m ON m."Id" = ry."MenuTanimiId" AND m."Kod" = 'sevk-sonrasi-duzeltme'
        JOIN "LookupYetkiTipleri" tip ON tip."Id" = ry."YetkiTipiId"
        ORDER BY r."Id"
    LOOP
        RAISE NOTICE 'Rol "%": sevk-sonrasi-duzeltme = %', satir.rol, satir.seviye;
    END LOOP;
END $$;

COMMIT;
