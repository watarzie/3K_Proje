    "UpdatedBy" text,
    CONSTRAINT "PK_EkipmanModelleri" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_EkipmanModelleri_EkipmanTipleri_TipId" FOREIGN KEY ("TipId") REFERENCES "EkipmanTipleri" ("Id") ON DELETE RESTRICT
