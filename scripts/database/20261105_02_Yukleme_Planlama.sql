);
CREATE INDEX IF NOT EXISTS "IX_EkipmanTipleri_AileId" ON "EkipmanTipleri" ("AileId");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_EkipmanTipleri_Kod" ON "EkipmanTipleri" ("Kod");

