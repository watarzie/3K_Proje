    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "PlanId" integer NOT NULL,
    "RevizyonId" integer NOT NULL,
    "RevizyonNo" integer NOT NULL,
    "Durum" smallint NOT NULL,
    "AracSayisi" integer NOT NULL,
    "ToplamYuk" integer NOT NULL,
    "BaslatanKullaniciId" integer,
    "BaslamaTarihi" timestamp without time zone NOT NULL,
    "KapatanKullaniciId" integer,
    "KapanisTarihi" timestamp without time zone,
    "KapanisGerekcesi" character varying(500),
    "CreatedDate" timestamp without time zone NOT NULL,
    "UpdatedDate" timestamp without time zone,
    "CreatedBy" text,
    "UpdatedBy" text,
