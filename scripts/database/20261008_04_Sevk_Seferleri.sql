-- =====================================================================================
-- Tır seferi (SevkSeferleri) ve sevkiyatın sefere bağlantısı (Sevkiyatlar."SevkSeferiId").
--
-- Sefer, aynı araçla aynı anda yapılan bir veya birden çok projenin sevkiyatlarını gruplar: toplu sevk bir sefer
-- ve proje başına bir sevkiyat yazar; tekil proje sevki de tek projelik bir sefer açar. Proje bazlı sevkiyat
-- kayıtları, proje içi sevkiyat numaraları ve onları okuyan raporlar değişmez.
--
-- Mevcut sevkiyatlar boş "SevkSeferiId" ile kalır; istatistikte plaka + sevk günü ile "eski kayıt" seferi olarak
-- gruplanır. Veri taşınmaz. Tekrar çalıştırılabilir; nesne adları EF modeliyle aynıdır.
-- =====================================================================================
BEGIN;

CREATE TABLE IF NOT EXISTS "SevkSeferleri" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "SeferNo" character varying(40) NOT NULL,
    "AracPlaka" character varying(30),
    "Sofor" character varying(100),
    "DorsePlaka" character varying(30),
    "Aciklama" character varying(500),
    "SevkTarihi" timestamp without time zone NOT NULL,
    "KullaniciId" integer NOT NULL,
    "IslemAnahtari" uuid,
    "IstekHash" character varying(64),
    "CreatedDate" timestamp without time zone NOT NULL,
    "UpdatedDate" timestamp without time zone,
    "CreatedBy" text,
    "UpdatedBy" text,
    CONSTRAINT "PK_SevkSeferleri" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_SevkSeferleri_Kullanicilar_KullaniciId" FOREIGN KEY ("KullaniciId") REFERENCES "Kullanicilar" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_SevkSeferleri_SeferNo" ON "SevkSeferleri" ("SeferNo");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_SevkSeferleri_IslemAnahtari" ON "SevkSeferleri" ("IslemAnahtari") WHERE "IslemAnahtari" IS NOT NULL;
CREATE INDEX IF NOT EXISTS "IX_SevkSeferleri_SevkTarihi" ON "SevkSeferleri" ("SevkTarihi");
CREATE INDEX IF NOT EXISTS "IX_SevkSeferleri_AracPlaka" ON "SevkSeferleri" ("AracPlaka");
CREATE INDEX IF NOT EXISTS "IX_SevkSeferleri_KullaniciId" ON "SevkSeferleri" ("KullaniciId");

ALTER TABLE "Sevkiyatlar" ADD COLUMN IF NOT EXISTS "SevkSeferiId" integer NULL;
CREATE INDEX IF NOT EXISTS "IX_Sevkiyatlar_SevkSeferiId" ON "Sevkiyatlar" ("SevkSeferiId");

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_Sevkiyatlar_SevkSeferleri_SevkSeferiId') THEN
        ALTER TABLE "Sevkiyatlar"
            ADD CONSTRAINT "FK_Sevkiyatlar_SevkSeferleri_SevkSeferiId"
            FOREIGN KEY ("SevkSeferiId") REFERENCES "SevkSeferleri" ("Id") ON DELETE RESTRICT;
    END IF;
END $$;

COMMIT;
