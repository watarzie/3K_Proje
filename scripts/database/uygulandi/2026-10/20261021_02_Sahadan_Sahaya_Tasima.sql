-- Saha satırları (sayaçlarıyla) bir saha projesinden diğerine taşınır; satır kopyalanmaz. Bu betik:
--   * "SahaAktarimlari": "KaynakSahaProjeId" (taşımada satırların geldiği saha projesi; proje silinirse boşalır) ve
--     "IslemAnahtari" (istemcinin tekrar anahtarı, boş değilse benzersiz) kolonlarını ekler.
--   * "SahaTasimaKalemleri": taşınan her satırın izini (kaynak/hedef saha ve sandık, miktar, tarih) tutan tabloyu kurar.
--     Taşıma başlığı, kaynak/hedef saha projesi, sandık ya da saha satırı silinirse bağ boşalır, iz kalır (numaralar
--     kopyadır); yalnız kök normal satır silinirse iz de silinir. A→B→C zincirinde ara saha B silinse de A→B adımı kalır.
-- Yıkıcı değildir, tekrar çalıştırılabilir. Yeni API başlamadan ÖNCE uygulanır (yeni API bu kolonları ve tabloyu her
-- saha aktarımı okumasında kullanır); eski API çalışırken uygulanabilir, eski API yeni kolonları kullanmaz.
-- Finans/Ambalaj tablosuna dokunmaz.
-- =====================================================================================
BEGIN;

ALTER TABLE "SahaAktarimlari" ADD COLUMN IF NOT EXISTS "KaynakSahaProjeId" integer NULL;
ALTER TABLE "SahaAktarimlari" ADD COLUMN IF NOT EXISTS "IslemAnahtari" uuid NULL;
CREATE INDEX IF NOT EXISTS "IX_SahaAktarimlari_KaynakSahaProjeId" ON "SahaAktarimlari" ("KaynakSahaProjeId");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_SahaAktarimlari_IslemAnahtari" ON "SahaAktarimlari" ("IslemAnahtari")
    WHERE "IslemAnahtari" IS NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_SahaAktarimlari_Projeler_KaynakSahaProjeId') THEN
        ALTER TABLE "SahaAktarimlari" ADD CONSTRAINT "FK_SahaAktarimlari_Projeler_KaynakSahaProjeId"
            FOREIGN KEY ("KaynakSahaProjeId") REFERENCES "Projeler" ("Id") ON DELETE SET NULL;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS "SahaTasimaKalemleri" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "SahaAktarimId" integer NULL,
    "SahaAktarimKalemiId" integer NULL,
    "OncekiSahaAktarimId" integer NULL,
    "KaynakCekiSatiriId" integer NOT NULL,
    "SahaCekiSatiriId" integer NULL,
    "KaynakSahaProjeId" integer NULL,
    "KaynakSahaProjeNo" text NOT NULL,
    "KaynakSahaSandikId" integer NULL,
    "KaynakSahaSandikNo" text NOT NULL,
    "HedefSahaProjeId" integer NULL,
    "HedefSahaProjeNo" text NOT NULL,
    "HedefSahaSandikId" integer NULL,
    "HedefSahaSandikNo" text NOT NULL,
    "Miktar" numeric(18,4) NOT NULL,
    "Tarih" timestamp without time zone NOT NULL,
    "CreatedDate" timestamp without time zone NOT NULL,
    "UpdatedDate" timestamp without time zone NULL,
    "CreatedBy" text NULL,
    "UpdatedBy" text NULL,
    CONSTRAINT "PK_SahaTasimaKalemleri" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_SahaTasimaKalemleri_SahaAktarimlari_SahaAktarimId"
        FOREIGN KEY ("SahaAktarimId") REFERENCES "SahaAktarimlari" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_SahaTasimaKalemleri_SahaAktarimKalemleri_SahaAktarimKalemiId"
        FOREIGN KEY ("SahaAktarimKalemiId") REFERENCES "SahaAktarimKalemleri" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_SahaTasimaKalemleri_SahaAktarimlari_OncekiSahaAktarimId"
        FOREIGN KEY ("OncekiSahaAktarimId") REFERENCES "SahaAktarimlari" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_SahaTasimaKalemleri_CekiSatirlari_KaynakCekiSatiriId"
        FOREIGN KEY ("KaynakCekiSatiriId") REFERENCES "CekiSatirlari" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_SahaTasimaKalemleri_CekiSatirlari_SahaCekiSatiriId"
        FOREIGN KEY ("SahaCekiSatiriId") REFERENCES "CekiSatirlari" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_SahaTasimaKalemleri_Projeler_KaynakSahaProjeId"
        FOREIGN KEY ("KaynakSahaProjeId") REFERENCES "Projeler" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_SahaTasimaKalemleri_Projeler_HedefSahaProjeId"
        FOREIGN KEY ("HedefSahaProjeId") REFERENCES "Projeler" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_SahaTasimaKalemleri_Sandiklar_KaynakSahaSandikId"
        FOREIGN KEY ("KaynakSahaSandikId") REFERENCES "Sandiklar" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_SahaTasimaKalemleri_Sandiklar_HedefSahaSandikId"
        FOREIGN KEY ("HedefSahaSandikId") REFERENCES "Sandiklar" ("Id") ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS "IX_SahaTasimaKalemleri_SahaAktarimId" ON "SahaTasimaKalemleri" ("SahaAktarimId");
CREATE INDEX IF NOT EXISTS "IX_SahaTasimaKalemleri_SahaAktarimKalemiId" ON "SahaTasimaKalemleri" ("SahaAktarimKalemiId");
CREATE INDEX IF NOT EXISTS "IX_SahaTasimaKalemleri_OncekiSahaAktarimId" ON "SahaTasimaKalemleri" ("OncekiSahaAktarimId");
CREATE INDEX IF NOT EXISTS "IX_SahaTasimaKalemleri_KaynakCekiSatiriId" ON "SahaTasimaKalemleri" ("KaynakCekiSatiriId");
CREATE INDEX IF NOT EXISTS "IX_SahaTasimaKalemleri_SahaCekiSatiriId" ON "SahaTasimaKalemleri" ("SahaCekiSatiriId");
CREATE INDEX IF NOT EXISTS "IX_SahaTasimaKalemleri_KaynakSahaProjeId" ON "SahaTasimaKalemleri" ("KaynakSahaProjeId");
CREATE INDEX IF NOT EXISTS "IX_SahaTasimaKalemleri_HedefSahaProjeId" ON "SahaTasimaKalemleri" ("HedefSahaProjeId");
CREATE INDEX IF NOT EXISTS "IX_SahaTasimaKalemleri_KaynakSahaSandikId" ON "SahaTasimaKalemleri" ("KaynakSahaSandikId");
CREATE INDEX IF NOT EXISTS "IX_SahaTasimaKalemleri_HedefSahaSandikId" ON "SahaTasimaKalemleri" ("HedefSahaSandikId");

COMMIT;
