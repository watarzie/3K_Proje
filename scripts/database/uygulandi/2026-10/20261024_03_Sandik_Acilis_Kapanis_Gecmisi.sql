-- Geçmiş aktarımı: yalnız tablo boşken (ilk çalıştırma). Yeni API yazmaya başladıktan sonra tekrar çalıştırma, aynı
-- işlemlerin hareket kayıtlarını ikinci kez aktarmaz (ilk çalıştırmada aktarılacak kayıt olmasa da).
DO $$
DECLARE
    aktarilan integer;
BEGIN
    IF EXISTS (SELECT 1 FROM "SandikDurumOlaylari") THEN
        RAISE NOTICE 'Olay tablosu dolu (geçmiş aktarılmış ya da uygulama yazmış); aktarım atlandı.';
        RETURN;
    END IF;

    WITH hareket AS (
        SELECT "ReferansId", "Islem", "IslemTipiId", "KullaniciId", "Tarih", "Aciklama", "YeniDeger"
        FROM "HareketGecmisleri" WHERE "ReferansTipi" = 'Sandik'
        UNION ALL
        SELECT "ReferansId", "Islem", "IslemTipiId", "KullaniciId", "Tarih", "Aciklama", "YeniDeger"
        FROM "HareketGecmisleriArsiv" WHERE "ReferansTipi" = 'Sandik'
    ), olay AS (
        SELECT h.*,
               -- Geri açılma önce: işlem tipi kapatma koduyla yazılmış olsa da metni geri açmadır.
               CASE
                   WHEN h."Islem" = 'Sandık Geri Açıldı' THEN 2
                   WHEN h."IslemTipiId" IN (14, 15, 18, 29)
                        OR h."Islem" IN ('Sandık Manuel Kapatma', 'Toplu Sandık Kapatma', 'Sandık Otomatik Hazır') THEN 1
               END AS tur
        FROM hareket h
        WHERE h."ReferansId" ~ '^[0-9]+$' AND length(h."ReferansId") <= 9
    )
    INSERT INTO "SandikDurumOlaylari" ("ProjeId", "SandikId", "SandikNo", "Tur", "Kaynak", "EskiDurumId", "YeniDurumId",
                                       "SebepId", "Not", "KullaniciId", "Tarih", "CreatedDate", "CreatedBy")
    SELECT s."ProjeId", s."Id", s."SandikNo", o.tur, 4, NULL,
           CASE WHEN o.tur = 1 THEN 3 WHEN o."YeniDeger" IN ('Bos', '1') THEN 1 ELSE 2 END, NULL,
           left('Geçmiş kayıt: ' || o."Islem" || coalesce(' – ' || nullif(btrim(o."Aciklama"), ''), ''), 500),
           k."Id", o."Tarih", now() AT TIME ZONE 'Europe/Istanbul', '20261024_03_Sandik_Acilis_Kapanis_Gecmisi.sql'
    FROM olay o
    JOIN "Sandiklar" s ON s."Id" = o."ReferansId"::integer
    LEFT JOIN "Kullanicilar" k ON k."Id" = o."KullaniciId"
    WHERE o.tur IS NOT NULL;
    GET DIAGNOSTICS aktarilan = ROW_COUNT;
    RAISE NOTICE 'Geçmişten aktarılan sandık olayı: %', aktarilan;
END $$;

-- Kapalı ve sevkli sandığın kapanma tarihi son kapanma olayıdır; ondan sonra geri açılma varsa (kapanışı iz bırakmamış)
-- tarih bilinmez ve boş kalır. Dolu tarih değiştirilmez.
UPDATE "Sandiklar" s
SET "KapanmaTarihi" = x.son_kapanma
FROM (
    SELECT "SandikId",
           max("Tarih") FILTER (WHERE "Tur" = 1) AS son_kapanma,
           max("Tarih") FILTER (WHERE "Tur" = 2) AS son_acilma
    FROM "SandikDurumOlaylari"
    WHERE "SandikId" IS NOT NULL
    GROUP BY "SandikId"
) x
WHERE s."Id" = x."SandikId"
  AND s."DurumId" IN (3, 4)
  AND s."KapanmaTarihi" IS NULL
  AND x.son_kapanma IS NOT NULL
  AND (x.son_acilma IS NULL OR x.son_kapanma >= x.son_acilma);

-- Hazırlanıyor/Boş sandıkta kapanma tarihi olmaz (betikle yeni API arasında eski API'nin geri açtığı sandık dahil).
UPDATE "Sandiklar" SET "KapanmaTarihi" = NULL WHERE "DurumId" IN (1, 2) AND "KapanmaTarihi" IS NOT NULL;

