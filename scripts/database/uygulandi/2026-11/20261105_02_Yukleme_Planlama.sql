-- ===== Ekipman kitaplığı =====
CREATE TABLE IF NOT EXISTS "EkipmanAileleri" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Kod" character varying(50) NOT NULL,
    "Ad" character varying(200) NOT NULL,
    "Sira" integer NOT NULL,
    "CreatedDate" timestamp without time zone NOT NULL,
    "UpdatedDate" timestamp without time zone,
    "CreatedBy" text,
    "UpdatedBy" text,
    CONSTRAINT "PK_EkipmanAileleri" PRIMARY KEY ("Id")
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_EkipmanAileleri_Kod" ON "EkipmanAileleri" ("Kod");

CREATE TABLE IF NOT EXISTS "EkipmanTipleri" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "AileId" integer NOT NULL,
    "Kod" character varying(50) NOT NULL,
    "Ad" character varying(200) NOT NULL,
