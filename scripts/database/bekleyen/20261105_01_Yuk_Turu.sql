-- (yeni API sandık okumalarında ve yükleme planında bu kolonu kullanır). Eski API çalışırken uygulanabilir (eski API
-- kolonu yazmaz, varsayılan 1 dolar). 31 numaralı betik (20261105_02_Yukleme_Planlama.sql) bu tabloyu kullanır; önce bu
-- betik çalışır. Finans/Ambalaj tablosuna dokunmaz.
