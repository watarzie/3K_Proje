-- Yıkıcı değildir, tekrar çalıştırılabilir: tablo/tohum/kolon/kısıt/indeks varsa eklenmez, var olan yük türüne
-- dokunulmaz. Sabit varsayılanlı NOT NULL kolon eklemek tabloyu yeniden yazmaz; FK doğrulaması Sandiklar'ı bir kez
