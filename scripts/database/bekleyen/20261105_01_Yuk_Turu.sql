BEGIN;

CREATE TABLE IF NOT EXISTS "LookupYukTurleri" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Anahtar" integer NOT NULL,
    "Deger" text NOT NULL,
    "CreatedDate" timestamp without time zone NOT NULL,
    "UpdatedDate" timestamp without time zone,
    "CreatedBy" text,
    "UpdatedBy" text,
    CONSTRAINT "PK_LookupYukTurleri" PRIMARY KEY ("Id")
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_LookupYukTurleri_Deger" ON "LookupYukTurleri" ("Deger");

INSERT INTO "LookupYukTurleri" ("Id", "Anahtar", "Deger", "CreatedDate")
VALUES (1, 1, 'Sandık', '2026-11-05'), (2, 2, 'Trafo', '2026-11-05'), (3, 3, 'Diğer özel yük', '2026-11-05')
ON CONFLICT DO NOTHING;
SELECT setval(pg_get_serial_sequence('"LookupYukTurleri"', 'Id'), (SELECT max("Id") FROM "LookupYukTurleri"));

ALTER TABLE "Sandiklar" ADD COLUMN IF NOT EXISTS "YukTuruId" integer NOT NULL DEFAULT 1;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_Sandiklar_LookupYukTurleri_YukTuruId') THEN
        ALTER TABLE "Sandiklar" ADD CONSTRAINT "FK_Sandiklar_LookupYukTurleri_YukTuruId"
            FOREIGN KEY ("YukTuruId") REFERENCES "LookupYukTurleri" ("Id") ON DELETE RESTRICT;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS "IX_Sandiklar_YukTuruId" ON "Sandiklar" ("YukTuruId");

DO $$
DECLARE
    satir record;
BEGIN
    FOR satir IN
        SELECT y."Deger" AS tur, count(s."Id") AS adet
        FROM "LookupYukTurleri" y
        LEFT JOIN "Sandiklar" s ON s."YukTuruId" = y."Id"
        GROUP BY y."Id", y."Deger"
        ORDER BY y."Id"
    LOOP
        RAISE NOTICE 'Yük türü "%": % sandık', satir.tur, satir.adet;
    END LOOP;
END $$;

-- Betik kaydı (README "Betik kaydı"): bu betiğin bu veritabanında çalıştığını aynı transaction içinde yazar.
CREATE TABLE IF NOT EXISTS "BetikKayitlari" (
    "BetikAdi"       text PRIMARY KEY,
    "UygulamaTarihi" timestamp without time zone NOT NULL,
    "Uygulayan"      text NOT NULL
);
INSERT INTO "BetikKayitlari" ("BetikAdi", "UygulamaTarihi", "Uygulayan")
VALUES ('20261105_01_Yuk_Turu', now() AT TIME ZONE 'Europe/Istanbul', current_user)
ON CONFLICT ("BetikAdi") DO NOTHING;

COMMIT;
